def _holiday_reply(name: str, casual: bool):
    name = {"설": "설날", "석가탄신일": "부처님 오신 날"}.get(name, re.sub(r"\s+", " ", name))
    today = datetime.now().date()
    if name in _HOLIDAYS:
        day = datetime.strptime(f"{today.year}-{_HOLIDAYS[name]}", "%Y-%m-%d").date()
        if day < today:
            day = day.replace(year=today.year + 1)
    else:
        day = next((d for d in (datetime.strptime(x, "%Y-%m-%d").date() for x in _LUNAR_HOLIDAYS[name]) if d >= today), None)
        if not day:
            return None
    text = f"{'다음 ' if day.year > today.year else ''}{name}{'은' if (ord(name[-1]) - 0xAC00) % 28 else '는'} {day.year}년 {day.month}월 {day.day}일 {_WEEKDAYS[day.weekday()]}요일이에요."
    return to_casual(text) if casual else text


