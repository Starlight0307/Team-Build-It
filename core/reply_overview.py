def report() -> str:
    lines = [f"📋 루미가 도와드릴 수 있는 일 · {len(FEATURES)}가지"]
    lines += [f"{title} — {', '.join(names)}" for title, names in GROUPS]
    return "\n".join(lines) + "\n\n" + CLOSING


def offers() -> list:
    return [Offer(label=name, func=EXAMPLE_FUNC, args={"name": name},
                  aliases=tuple(aliases) + (name,), which=WHICH, by_name=True, strict_name=True)
            for name, _desc, _examples, aliases in FEATURES]


def build():
    """-> (보고서 글, [Offer 16개])"""
    return report(), offers()


def example_reply(name) -> str:
    """기능 하나의 사용 예(대화체). 모르는 이름이면 None."""
    for fname, desc, examples, _aliases in FEATURES:
        if fname == name:
            quoted = ", ".join(f'"{e}"' for e in examples)
            return (f"{fname}은(는) {desc} 예를 들어 {quoted}처럼 말하면 돼요. "
                    "다른 기능의 사용 예도 알려 드릴까요?").replace("은(는)", "는" if _no_batchim(fname) else "은")
    return None


def _no_batchim(text: str) -> bool:
    last = str(text)[-1:]
    return "가" <= last <= "힣" and (ord(last) - 0xAC00) % 28 == 0


# ── "뭐 할 수 있어?" 같은 기능 소개 질문 (2026-11-17) ──
# 모델에 맡기면 "프로그램 설치, 업데이트…"처럼 없는 기능을 지어냈다. 문장 전체가 소개 질문일 때만(앞뒤에 다른 대상이 붙으면 아니다) 보고서로 답한다.
import re as _re

_OV_PREFIX = r"(?:그럼|혹시|그래서|이제|근데|자|음|저기)*(?P<who>루미야|루미가|루미는|루미|너희|너는|너가|넌|너)?(?:지금|이제|앞으로)?"
_OV_ANSWER = r"(?:알려줘|알려줄래|알려주세요|알려주라|말해줘|말해봐|말해주세요|가르쳐줘|보여줘|설명해줘|소개해줘|궁금해|뭐야|뭔데|뭐지|뭐니)?"
_OV_WHAT = r"(?:뭐|뭘|무엇을?|무슨일을?|어떤일을?|무슨걸|어떤걸|어떤것을)(?:을|를)?(?:다|또)?"
_OV_CAN = r"(?:할|해줄|도와줄|도울)수있"
_OV_PATTERNS = tuple(_re.compile(p) for p in (
    _OV_WHAT + r"(?:" + _OV_CAN + r"|할줄알)(?:어|어요|니|나|나요|는지|는데|는건지|지|냐|을까|아|아요)?" + _OV_ANSWER,
    r"(?:할|해줄|도와줄|도울)수있는(?:거|것|일|기능|걸|게|것들|거들)(?:이|가|은|는)?(?:뭐가있어|뭐있어|있어)?" + _OV_ANSWER,
    r"(?:루미)?(?:의)?(?:기능|능력)(?:이|들|은|을|목록)?(?:뭐가?있어|뭐있어|뭐야|뭔데|뭐지|목록|알려줘|알려줄래|알려주세요|보여줘|소개해줘|궁금해|있어)",
    r"(?:무슨|어떤)기능(?:이|들이)?(?:있어|있니|있나|있어요|들어있어)",
    r"도움말|help|헬프|사용설명서",
))
_OV_NEEDS_WHO = _re.compile(r"(?:뭐|뭘)(?:해줘|해줄수있어|도와줘|할줄알아)")


def is_overview_question(text) -> bool:
    """"뭐 할 수 있어?"·"기능 알려줘"·"도움말"처럼 루미 전체 기능을 묻는 문장인가.
    "이 파일로 뭐 할 수 있어", "파일 정리 할 수 있어?", "타이머 기능 알려줘"처럼 대상이 붙은 문장은 아니다."""
    t = _re.sub(r"[\s?!.~,ㅎㅋ]+", "", str(text or "").lower())
    if not t or len(t) > 40:
        return False
    m = _re.match(_OV_PREFIX, t)
    if not m:
        return False
    rest = t[m.end():]
    if not rest:
        return False
    if m.group("who") and _OV_NEEDS_WHO.fullmatch(rest):
        return True
    return any(p.fullmatch(rest) for p in _OV_PATTERNS)
