def report() -> str:
    lines = [f"📋 루미가 도와드릴 수 있는 일 · {len(FEATURES)}가지"]
    lines += [f"{title} — {', '.join(names)}" for title, names in GROUPS]
    return "\n".join(lines) + "\n\n" + CLOSING


def offers() -> list:
    return [Offer(label=name, func=EXAMPLE_FUNC, args={"name": name},
                  aliases=tuple(aliases) + (name,), which=WHICH, by_name=True, strict_name=True)
            for name, _desc, _examples, aliases in FEATURES]


def build():
    """-> (보고서 글, [Offer 15개])"""
    return report(), offers()


def example_reply(name) -> str:
    """기능 하나의 사용 예(대화체). 모르는 이름이면 None."""
    for fname, desc, examples, _aliases in FEATURES:
        if fname == name:
            quoted = ", ".join(f'"{e}"' for e in examples)
            return (f"{fname}은(는) {desc} 예를 들어 {quoted}처럼 말하면 돼요. "
                    "다른 기능의 사용 예도 알려 드릴까요?").replace("은(는)", "는" if _no_batchim(fname) else "은")
    return None


def _no_batchim(text: str) -> bool:
    last = str(text)[-1:]
    return "가" <= last <= "힣" and (ord(last) - 0xAC00) % 28 == 0
